const DICTS: Record<Lang, Dict> = { "zh-TW": zh, ja, en };
let current: Lang = "zh-TW";

/** 依作業系統語言猜預設語言 */
export function detectLang(): Lang {
  const l = navigator.language.toLowerCase();
  if (l.startsWith("ja")) return "ja";
  if (l.startsWith("zh")) return "zh-TW";
  return "en";
}

export function setLang(lang: Lang): void {
  current = DICTS[lang] ? lang : "zh-TW";
  document.documentElement.lang = current === "zh-TW" ? "zh-Hant" : current;
}

export function getLang(): Lang {
  return current;
}

/** 取得文字；{name} 會被 vars 裡的值取代 */
export function t(key: string, vars: Record<string, string | number> = {}): string {
  let s = DICTS[current][key] ?? zh[key] ?? key;
  for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

/** 套用到頁面上所有 data-i18n / data-i18n-placeholder 元素 */
export function applyI18n(root: ParentNode = document): void {
  root.querySelectorAll<HTMLElement>("[data-i18n]").forEach((el) => (el.textContent = t(el.dataset.i18n!)));
  root.querySelectorAll<HTMLInputElement>("[data-i18n-placeholder]").forEach((el) => (el.placeholder = t(el.dataset.i18nPlaceholder!)));
  root.querySelectorAll<HTMLElement>("[data-i18n-title]").forEach((el) => (el.title = t(el.dataset.i18nTitle!)));
}
